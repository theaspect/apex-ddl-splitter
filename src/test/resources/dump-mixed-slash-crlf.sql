CREATE TABLE  "ITEM"
   (	"ID" NUMBER GENERATED ALWAYS AS IDENTITY NOT NULL ENABLE,
	"NAME" VARCHAR2(128),
	 CONSTRAINT "ITEM_PK" PRIMARY KEY ("ID")
  USING INDEX  ENABLE
   ) ;
  CREATE UNIQUE INDEX  "ITEM_IDX1" ON  "ITEM" ("NAME")
/
ALTER TABLE  "ITEM" ADD CONSTRAINT "ITEM_UK1" UNIQUE ("NAME")
  USING INDEX  "ITEM_IDX1"  ENABLE
/
CREATE OR REPLACE EDITIONABLE PACKAGE  "UTIL_PKG" AS
  FUNCTION get_id(p_name IN VARCHAR2) RETURN NUMBER;
END UTIL_PKG;
/
CREATE OR REPLACE EDITIONABLE PACKAGE BODY  "UTIL_PKG" AS
  FUNCTION get_id(p_name IN VARCHAR2) RETURN NUMBER IS
    l_id NUMBER;
  BEGIN
    SELECT "ID" INTO l_id FROM "ITEM" WHERE "NAME" = p_name;
    RETURN l_id;
  END get_id;
END UTIL_PKG;
/
